/* Service worker: offline app shell for the Block Pix game (PWA). */
const CACHE = 'blockpix-v1';
const ASSETS = [
  './',
  './index.html',
  './manifest.webmanifest',
  './assets/block-buddy.png',
  './assets/puzzle-block.png',
  './assets/star-gem.png',
  './assets/bomb-block.png',
  './assets/dreamy-sky-background.png',
  './icons/icon-192.png',
  './icons/icon-512.png',
  './icons/icon-maskable-512.png',
  './icons/apple-touch-icon.png',
  './icons/favicon-32.png',
  './icons/favicon-16.png'
];

self.addEventListener('install', (e) => {
  e.waitUntil(
    caches.open(CACHE)
      .then((c) => c.addAll(ASSETS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  e.respondWith(
    caches.match(req).then((hit) => {
      if (hit) return hit;
      return fetch(req)
        .then((res) => {
          // runtime-cache successful same-origin GETs
          if (res && res.ok && new URL(req.url).origin === self.location.origin) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(() => {
          // offline fallback: serve the app shell for navigations
          if (req.mode === 'navigate') return caches.match('./index.html');
        });
    })
  );
});
